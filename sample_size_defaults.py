"""Generate and serve the default sample-size plots from the deployed evidence."""
from __future__ import annotations

import argparse
from functools import lru_cache
import hashlib
import json
import math
import os
import re
from pathlib import Path
import subprocess
import tempfile

CATALOG = '/api/sample-size-summary/catalog'
SUMMARY = '/api/sample-size-summary'
FILE = 'data/sample_size_defaults.json'
VERSION = 2


def _revision(root, ref='HEAD'):
    """Identify the release tree without including its derived snapshot."""
    root = root.resolve()
    try:
        top = Path(subprocess.check_output(
            ['git', 'rev-parse', '--show-toplevel'], cwd=root, stderr=subprocess.DEVNULL
        ).decode().strip()).resolve()
        path = (root / FILE).relative_to(top).as_posix().encode()
        entries = subprocess.check_output(
            ['git', 'ls-tree', '-rz', '--full-tree', ref],
            cwd=root, stderr=subprocess.DEVNULL,
        )
    except (OSError, ValueError, subprocess.CalledProcessError):
        return None
    digest = hashlib.sha256()
    for entry in entries.split(b'\0'):
        if entry and entry.partition(b'\t')[2] != path:
            digest.update(entry + b'\0')
    return digest.hexdigest()


@lru_cache(maxsize=8)
def _read(path, modified, size):
    doc = json.loads(path.read_text())
    return doc if doc['version'] == VERSION else None


@lru_cache(maxsize=8)
def _file_digest(path, modified, size):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _attested_archive(path, stat):
    # GitHub-triggered Railway archives advertise their originating commit.
    # A release may pin the exact generated bytes there to skip re-pooling.
    trailer = re.search(r'^Sample-Size-SHA256: ([0-9a-f]{64})$',
                        os.environ.get('RAILWAY_GIT_COMMIT_MESSAGE', ''), re.MULTILINE)
    return bool(trailer and trailer[1] == _file_digest(path, stat.st_mtime_ns, stat.st_size))


def _load(root, revision):
    path = root / FILE
    try:
        stat = path.stat()
        bundle = _read(path, stat.st_mtime_ns, stat.st_size)
        if bundle and (bundle['source_revision'] == revision
                       or (revision is None and (bundle.get('built_for_deployment') is True
                                                or _attested_archive(path, stat)))):
            return bundle
    except (OSError, KeyError, ValueError, TypeError):
        pass
    return None


def _equal(raw, default):
    if isinstance(default, bool):
        return raw.lower() in ({'1', 'yes', 'true'} if default else {'0', 'no', 'false'})
    if isinstance(default, (int, float)):
        try:
            return math.isfinite(float(raw)) and float(raw) == default
        except ValueError:
            return False
    return isinstance(default, str) and raw == default


def _default_query(catalog, profile, summary):
    defaults = {
        'keep_latest_cohort': True, 'include_preprints': False,
        'include_subexposures': 'yes', 'arms': 2, 'max_sample_size': 20000,
        'smoking_status': 'all', 'ethnicity': 'all', 'gender': 'all',
    }
    current = (summary or {}).get('analysis_settings', catalog.get('analysis_settings', {}))
    for name, value in current.items():
        if name in ('baseline_source', 'age', 'years', 'sex', 'race'):
            defaults[name] = value
    if profile == 'onco':
        defaults['mode'] = 'combined'
        if not current:
            defaults.update(baseline_source='seer', age=60, years=10, sex='site_default')
    elif profile == 'uro':
        if summary is None:
            # The prostate and bladder workers have different default sexes.
            defaults.update(baseline_source='seer', age=60, years=10,
                            race='all_races_ethnicities')
    elif profile == 'neuro':
        defaults.update(incidenceStartAge=65, incidenceYears=10, incidenceSex='both')
    defaults['latest_cohort'] = defaults['keep_latest_cohort']
    defaults.update(catalog['defaults'])
    return defaults


def _defaults_match(args, catalog, profile, summary):
    if any(len(values) != 1 for _, values in args.lists()):
        return False
    defaults = _default_query(catalog, profile, summary)
    for key, value in args.items():
        if key in {'lang', 'disease', 'scope', 'outcome', 'exposure', 'exposures', 'max_sample_size',
                   'effect_measure', 'forest_scale', 'study_design', 'studyDesign',
                   'exposure_rate', 'controls_per_case', 'controlExposurePercent',
                   'controlsPerCase'}:
            continue
        if summary is None and key in catalog['defaults']:
            continue
        if key in ('age', 'years', 'incidenceStartAge', 'incidenceYears') and not value.strip().isdecimal():
            return False
        if key == 'sidedness' and value.lower() == '2':
            value = 'two'
        if not _equal(value, defaults.get(key)):
            return False
    return True


def _choose_disease(args, catalog, profile):
    diseases = catalog['diseases']
    wanted = (args.get('outcome') if profile == 'neuro' else '') or args.get('disease') or args.get('scope')
    if not wanted:
        return diseases[0] if diseases else None

    def normalize(text):
        return re.sub('[^a-z0-9]+', '_', str(text).lower()).strip('_')

    key = normalize(wanted)
    for item in diseases:
        if any(normalize(name) == key for name in (item['value'], item['label'], *item.get('aliases', []))):
            return item
    return None


def build_pages(bundle):
    from sample_size_prerender import render_default_panels
    return {item['value']: render_default_panels(bundle['summaries'][item['value']], item['label'])
            for item in bundle['catalog']['diseases']}


def install(app, profile='standard', root=None):
    """Short-circuit only matching requests, before pooling or starting workers."""
    from flask import jsonify, request

    root = Path(root or app.root_path).resolve()

    @lru_cache(maxsize=1)
    def release():
        return _revision(root)

    def current_bundle():
        if app.config.get('SAMPLE_SIZE_DEFAULTS_DISABLED'):
            return None
        if 'include_subexposures' not in request.args:
            for key in ('include_subexposures', 'metaGut_subexposures', 'metaFemina_subexposures'):
                if request.cookies.get(key, '').lower() in ('no', 'false', '0'):
                    return None
        bundle = _load(root, release())
        return bundle if bundle and bundle['profile'] == profile else None

    def initial_page():
        from sample_size_prerender import default_planning_context
        bundle = current_bundle()
        if bundle is None:
            return None
        catalog = bundle['catalog']
        selected = _choose_disease(request.args, catalog, profile)
        if not selected:
            return None
        summary = bundle['summaries'][selected['value']]
        if not _defaults_match(request.args, catalog, profile, summary):
            return None
        if not _equal(request.args.get('max_sample_size', '20000'), 20000):
            return None
        query = _default_query(catalog, profile, summary)
        return dict(bootstrap=dict(catalog=catalog, summary=summary, query=query),
                    selected=selected, context=default_planning_context(summary),
                    panels=bundle['pages'][selected['value']])

    @app.context_processor
    def sample_size_first_paint():
        if request.path == '/sample-size-summary':
            return {'sample_initial': page_for_request()}
        return {}

    def page_for_request():
        from flask import g
        if 'sample_size_initial' not in g:
            g.sample_size_initial = initial_page()
        return g.sample_size_initial

    @app.before_request
    def default_sample_size():
        if (app.config.get('SAMPLE_SIZE_DEFAULTS_DISABLED')
                or request.method not in ('GET', 'HEAD')
                or request.path not in (CATALOG, SUMMARY)):
            return None
        bundle = current_bundle()
        if not bundle:
            return None
        catalog = bundle['catalog']
        # The page always submits a catalog ID. Leave aliases, errors and
        # implicit endpoint selection to the existing live handler.
        summary = None
        if request.path == SUMMARY:
            summary = bundle['summaries'].get(request.args.get('disease'))
            if summary is None:
                return None
        if not _defaults_match(request.args, catalog, profile, summary):
            return None
        data = catalog if summary is None else summary
        response = jsonify(data)
        response.headers['X-Sample-Size-Source'] = 'precomputed'
        return response


    return page_for_request


def _write_bundle(root, bundle):
    path = root / FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile('w', dir=path.parent, delete=False, encoding='utf-8') as stream:
        temporary = Path(stream.name)
        try:
            json.dump(bundle, stream, ensure_ascii=False, allow_nan=False,
                      separators=(',', ':'), sort_keys=True)
            stream.write('\n')
            stream.flush()
            temporary.chmod(0o644)
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


def generate(app, root, profile, force=False, deployment=False):
    revision = _revision(root)
    existing = None if force else _load(root, revision)
    if (existing and existing['profile'] == profile
            and (revision is not None or _attested_archive(root / FILE, (root / FILE).stat()))
            and set(existing['pages']) == set(existing['summaries'])
            and set(existing['summaries']) == {d['value'] for d in existing['catalog']['diseases']}):
        if deployment and not existing.get('built_for_deployment'):
            _write_bundle(root, {**existing, 'built_for_deployment': True})
        print(f"Default sample size plots already prepared for {len(existing['summaries'])} outcomes.", flush=True)
        return
    previous = {key: app.config.get(key) for key in ('SAMPLE_SIZE_DEFAULTS_DISABLED', 'SAMPLE_SIZE_BUILD')}
    app.config['SAMPLE_SIZE_DEFAULTS_DISABLED'] = True
    app.config['SAMPLE_SIZE_BUILD'] = {}
    client = app.test_client()

    def fetch(path, **params):
        response = client.get(path, query_string=params)
        if response.status_code != 200:
            raise RuntimeError(f'{path} {params}: HTTP {response.status_code}: {response.get_json(silent=True)}')
        return response.get_json()

    try:
        catalog = fetch(CATALOG)
        if not catalog['diseases']:
            raise ValueError('The sample size catalog has no outcomes.')
        summaries = {}
        for disease in catalog['diseases']:
            label = disease['value']
            summary = fetch(SUMMARY, disease=label)
            if summary['disease'] != label or len(summary['panels']) != 4:
                raise ValueError(f'Invalid sample size results for {label}')
            summaries[label] = summary
            print(f'{len(summaries)}/{len(catalog["diseases"])} {label}', flush=True)
        bundle = dict(version=VERSION, source_revision=revision, profile=profile,
                      catalog=catalog, summaries=summaries)
        bundle['pages'] = build_pages(bundle)
        if deployment:
            bundle['built_for_deployment'] = True
        _write_bundle(root, bundle)
    finally:
        app.config.update(previous)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', choices=('standard', 'neuro', 'onco', 'uro'), default='standard')
    parser.add_argument('--force', action='store_true')
    parser.add_argument('--deployment', action='store_true', help='Prepare the snapshot inside the deployed image.')
    options = parser.parse_args()
    from app import app

    generate(app, Path(__file__).resolve().parent, options.profile, options.force, options.deployment)


if __name__ == '__main__':
    main()
